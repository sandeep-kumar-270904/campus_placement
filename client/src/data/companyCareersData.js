/**
 * Filter companies by category, search text, and hiring attributes
 */
export function filterCompanies(companies, { category = 'All', search = '', fresherOnly = false, internOnly = false }) {
  return companies.filter((company) => {
    // 1. Category Filter
    if (category !== 'All' && company.type !== category) {
      return false;
    }

    // 2. Fresher Friendly filter
    if (fresherOnly && !company.fresherFriendly) {
      return false;
    }

    // 3. Internship hiring filter
    if (internOnly && !company.internshipHiring) {
      return false;
    }

    // 4. Keyword search
    if (search.trim()) {
      const q = search.toLowerCase();
      const matchName = company.name.toLowerCase().includes(q);
      const matchIndustry = company.industry.toLowerCase().includes(q);
      const matchTagline = company.tagline.toLowerCase().includes(q);
      const matchRoles = company.roles.some((r) => r.toLowerCase().includes(q));
      const matchHubs = company.indiaHubs.some((h) => h.toLowerCase().includes(q));
      const matchTags = (company.hiringTags || []).some((t) => t.toLowerCase().includes(q));

      return matchName || matchIndustry || matchTagline || matchRoles || matchHubs || matchTags;
    }

    return true;
  });
}
